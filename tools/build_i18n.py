"""Moves translations between locale/*.po and plunderhub/i18n.py.

The .po files are what translators work on - standard gettext format,
which Weblate, Crowdin, Poedit and every other translation tool already
understands. i18n.py stays the file the app actually reads, so there's
no gettext dependency at runtime and a plain checkout just works.

    python3 tools/build_i18n.py export   # i18n.py  -> locale/*.po
    python3 tools/build_i18n.py import   # locale/*.po -> i18n.py
    python3 tools/build_i18n.py check    # verify the two agree

`import` is the one to run after translations come back. `check` is what
tests/test_i18n.py calls, so the two can't drift unnoticed.

msgid is the string key (e.g. "sort_by"), not the English text, matching
how the app looks strings up. English lives in locale/en.po like any
other language rather than being the msgid, so a wording change in
English doesn't invalidate every translation of it.
"""

import argparse
import ast
import re
import sys
from pathlib import Path
from typing import Dict, List, Tuple

REPO = Path(__file__).resolve().parent.parent
I18N_PY = REPO / "plunderhub" / "i18n.py"
LOCALE_DIR = REPO / "locale"

# Shown in each .po header so translators know what they're working on.
LANG_NAMES = {
    "en": "English",
    "hu": "Magyar",
    "de": "Deutsch",
    "fr": "Francais",
    "es": "Espanol",
    "pl": "Polski",
    "pt_br": "Portugues (Brasil)",
    "ru": "Russian",
    "uk": "Ukrainian",
}


def load_strings() -> Dict[str, Dict[str, str]]:
    """The STRINGS table from i18n.py.

    Parsed out of the source rather than imported, so this runs without
    PyGObject/GTK present (i18n.py itself is import-safe, but the rest of
    the package it sits in is not, and a translator shouldn't need the
    whole GUI stack installed to regenerate a catalog)."""
    source = I18N_PY.read_text(encoding="utf-8")
    tree = ast.parse(source)
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else (
            [node.target] if isinstance(node, ast.AnnAssign) else [])
        for target in targets:
            if isinstance(target, ast.Name) and target.id == "STRINGS":
                return ast.literal_eval(node.value)
    raise SystemExit("No STRINGS table found in i18n.py")


def po_escape(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"')
    return out.replace("\n", "\\n").replace("\t", "\\t")


def po_unescape(text: str) -> str:
    out = ""
    i = 0
    while i < len(text):
        if text[i] == "\\" and i + 1 < len(text):
            out += {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}.get(text[i + 1], text[i + 1])
            i += 2
        else:
            out += text[i]
            i += 1
    return out


def write_po(lang: str, entries: Dict[str, str], english: Dict[str, str]) -> Path:
    lines = [
        f'# PlunderHub translations - {LANG_NAMES.get(lang, lang)}',
        '#',
        '# Generated by tools/build_i18n.py. Edit the msgstr lines, then run',
        '#   python3 tools/build_i18n.py import',
        '# to fold the changes back into plunderhub/i18n.py.',
        '#',
        '# msgid is the lookup key used in the code, not English text. The',
        '# English wording is shown above each entry as a comment, and lives',
        '# in locale/en.po as a translation like any other.',
        '#',
        '# Keep {placeholders} exactly as they appear - the app formats these',
        '# by name, and tests/test_i18n.py fails the build if any go missing.',
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: PlunderHub\\n"',
        f'"Language: {lang}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '',
    ]
    for key in sorted(english):
        reference = english[key]
        if lang != "en":
            lines.append(f'#. English: {po_escape(reference)}')
        lines.append(f'msgid "{po_escape(key)}"')
        lines.append(f'msgstr "{po_escape(entries.get(key, ""))}"')
        lines.append('')
    path = LOCALE_DIR / f"{lang}.po"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def read_po(path: Path) -> Dict[str, str]:
    """Parses a .po file into {msgid: msgstr}.

    Deliberately minimal: it only needs to read back what write_po
    produces, plus whatever a translation tool round-trips through -
    multi-line string continuations and comments. Plural forms and
    contexts aren't used by this app and aren't handled."""
    entries: Dict[str, str] = {}
    key = None
    field = None
    buffers: Dict[str, List[str]] = {"msgid": [], "msgstr": []}

    def flush():
        nonlocal key
        msgid = "".join(buffers["msgid"])
        if msgid:
            entries[msgid] = "".join(buffers["msgstr"])
        buffers["msgid"] = []
        buffers["msgstr"] = []
        key = None

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = re.match(r'^(msgid|msgstr)\s+"(.*)"$', line)
        if match:
            if match.group(1) == "msgid":
                flush()
            field = match.group(1)
            buffers[field].append(po_unescape(match.group(2)))
            continue
        continuation = re.match(r'^"(.*)"$', line)
        if continuation and field:
            buffers[field].append(po_unescape(continuation.group(1)))
    flush()
    return entries


def render_strings(strings: Dict[str, Dict[str, str]]) -> str:
    """The STRINGS literal, formatted the way i18n.py already has it."""
    english = strings["en"]
    out = ["STRINGS: Dict[str, Dict[str, str]] = {"]
    for lang in strings:
        out.append(f'    "{lang}": {{')
        for key in sorted(english):
            value = strings[lang].get(key, english[key])
            out.append(f'        {key!r}: {value!r},')
        out.append("    },")
    out.append("}")
    return "\n".join(out)


def replace_strings_block(source: str, rendered: str) -> str:
    tree = ast.parse(source)
    for node in tree.body:
        targets = node.targets if isinstance(node, ast.Assign) else (
            [node.target] if isinstance(node, ast.AnnAssign) else [])
        for target in targets:
            if isinstance(target, ast.Name) and target.id == "STRINGS":
                lines = source.splitlines(keepends=True)
                head = "".join(lines[:node.lineno - 1])
                tail = "".join(lines[node.end_lineno:])
                return head + rendered + "\n" + tail
    raise SystemExit("No STRINGS table found in i18n.py")


def cmd_export() -> int:
    strings = load_strings()
    LOCALE_DIR.mkdir(exist_ok=True)
    english = strings["en"]
    for lang in strings:
        path = write_po(lang, strings[lang], english)
        print(f"wrote {path.relative_to(REPO)} ({len(english)} entries)")
    return 0


def cmd_import() -> int:
    strings = load_strings()
    english = read_po(LOCALE_DIR / "en.po")
    updated: Dict[str, Dict[str, str]] = {}
    for lang in strings:
        path = LOCALE_DIR / f"{lang}.po"
        if not path.exists():
            print(f"warning: {path.name} missing, keeping the existing {lang} strings")
            updated[lang] = strings[lang]
            continue
        entries = read_po(path)
        missing = [k for k in english if not entries.get(k)]
        if missing:
            print(f"warning: {lang} has {len(missing)} untranslated key(s), "
                  f"falling back to English for those")
        updated[lang] = {k: entries.get(k) or english[k] for k in english}
    source = I18N_PY.read_text(encoding="utf-8")
    I18N_PY.write_text(replace_strings_block(source, render_strings(updated)), encoding="utf-8")
    print(f"updated {I18N_PY.relative_to(REPO)} from {len(updated)} catalog(s)")
    return 0


def differences() -> List[Tuple[str, str, str]]:
    """Every place locale/*.po and i18n.py disagree."""
    strings = load_strings()
    out = []
    for lang, table in strings.items():
        path = LOCALE_DIR / f"{lang}.po"
        if not path.exists():
            out.append((lang, "-", f"locale/{lang}.po is missing"))
            continue
        entries = read_po(path)
        for key in sorted(set(table) | set(entries)):
            in_py = table.get(key)
            in_po = entries.get(key)
            if in_py != in_po:
                out.append((lang, key, f"i18n.py={in_py!r} po={in_po!r}"))
    return out


def cmd_check() -> int:
    diffs = differences()
    if not diffs:
        print("locale/*.po and i18n.py agree")
        return 0
    print(f"{len(diffs)} difference(s) between locale/*.po and i18n.py:")
    for lang, key, detail in diffs[:20]:
        print(f"  [{lang}] {key}: {detail}")
    print("\nRun `python3 tools/build_i18n.py export` (or `import`) to resync.")
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("export", "import", "check"))
    args = parser.parse_args()
    return {"export": cmd_export, "import": cmd_import, "check": cmd_check}[args.command]()


if __name__ == "__main__":
    sys.exit(main())
